-- YardZone: outline geometry, validation, and the editor behind the
-- build-menu yard tool (draw, close, drag, insert, delete, undo).

local function setup()
    local world = stubs.install()
    world:load("src/YardZone.lua")
    return world
end

local function square(x, z, size)
    return { { x = x, z = z }, { x = x + size, z = z }, { x = x + size, z = z + size }, { x = x, z = z + size } }
end

-- Geometry -----------------------------------------------------------------------------------

test("area of a square, either winding", function()
    setup()
    local s = square(0, 0, 10)
    assertNear(YardZone.area(s), 100, 1e-9)
    local reversed = { s[4], s[3], s[2], s[1] }
    assertNear(YardZone.area(reversed), 100, 1e-9)
    assertTrue(YardZone.signedArea(s) * YardZone.signedArea(reversed) < 0)
end)

test("crossing and touching segments intersect; parallel ones don't", function()
    setup()
    assertTrue(YardZone.segmentsIntersect(0, 0, 10, 10, 0, 10, 10, 0), "cross")
    assertTrue(YardZone.segmentsIntersect(0, 0, 10, 0, 5, 0, 5, 5), "T touch")
    assertTrue(YardZone.segmentsIntersect(0, 0, 10, 0, 5, 0, 15, 0), "collinear overlap")
    assertTrue(not YardZone.segmentsIntersect(0, 0, 10, 0, 0, 1, 10, 1), "parallel")
    assertTrue(not YardZone.segmentsIntersect(0, 0, 10, 0, 11, 0, 20, 0), "collinear apart")
end)

test("a bow-tie crosses itself, a square doesn't", function()
    setup()
    assertTrue(not YardZone.isSelfIntersecting(square(0, 0, 10)))
    local bowTie = { { x = 0, z = 0 }, { x = 10, z = 10 }, { x = 10, z = 0 }, { x = 0, z = 10 } }
    assertTrue(YardZone.isSelfIntersecting(bowTie))
end)

test("an outline folding back on itself is self-intersecting", function()
    setup()
    local spike = { { x = 0, z = 0 }, { x = 10, z = 0 }, { x = 5, z = 0 }, { x = 5, z = 10 } }
    assertTrue(YardZone.isSelfIntersecting(spike))
end)

test("overlap: crossing, nested and apart", function()
    setup()
    assertTrue(YardZone.polygonsOverlap(square(0, 0, 10), square(5, 5, 10)), "crossing")
    assertTrue(YardZone.polygonsOverlap(square(0, 0, 30), square(10, 10, 5)), "inside")
    assertTrue(YardZone.polygonsOverlap(square(10, 10, 5), square(0, 0, 30)), "contains")
    assertTrue(not YardZone.polygonsOverlap(square(0, 0, 10), square(20, 0, 10)), "apart")
end)

test("nearest corner and edge within reach", function()
    setup()
    local s = square(0, 0, 10)
    local index, distance = YardZone.nearestVertex(s, 10.5, 0.5, 1.5)
    assertEquals(index, 2)
    assertNear(distance, math.sqrt(0.5), 1e-9)
    assertEquals(YardZone.nearestVertex(s, 5, 5, 1.5), nil)
    local edge, px, pz = YardZone.nearestEdge(s, 5, -0.5, 1)
    assertEquals(edge, 1)
    assertNear(px, 5, 1e-9)
    assertNear(pz, 0, 1e-9)
    local closing = YardZone.nearestEdge(s, -0.5, 5, 1)
    assertEquals(closing, 4, "the closing edge from the last corner to the first")
    assertEquals(YardZone.nearestEdge(s, -0.5, 5, 1, false), nil, "open outlines have no closing edge")
end)

test("validation accepts a plain yard and names what's wrong otherwise", function()
    setup()
    local E = YardZone.ERROR
    assertTrue(YardZone.validate(square(0, 0, 20), {}))
    local ok, err = YardZone.validate({ { x = 0, z = 0 }, { x = 10, z = 0 } }, {})
    assertTrue(not ok)
    assertEquals(err, E.TOO_FEW_POINTS)
    _, err = YardZone.validate(square(0, 0, 5), {})
    assertEquals(err, E.TOO_SMALL)
    _, err = YardZone.validate({ { x = 0, z = 0 }, { x = 20, z = 0 }, { x = 20, z = 20 }, { x = 20.5, z = 20 },
        { x = 0, z = 20 } }, {})
    assertEquals(err, E.EDGE_TOO_SHORT)
    _, err = YardZone.validate({ { x = 0, z = 0 }, { x = 20, z = 20 }, { x = 20, z = 0 }, { x = 0, z = 20 } }, {})
    assertEquals(err, E.SELF_INTERSECTING)
    _, err = YardZone.validate(square(0, 0, 20), { square(10, 10, 20) })
    assertEquals(err, E.OVERLAPS_YARD)
    local many = {}
    for i = 1, 70 do
        local a = (i - 1) / 70 * 2 * math.pi
        many[i] = { x = 100 * math.cos(a), z = 100 * math.sin(a) }
    end
    _, err = YardZone.validate(many, {})
    assertEquals(err, E.TOO_MANY_POINTS)
end)

test("cleaning drops a closing corner that repeats the first, and near-duplicates", function()
    setup()
    local fence = { { x = 0, z = 0 }, { x = 10, z = 0 }, { x = 10.3, z = 0.2 }, { x = 10, z = 10 },
        { x = 0, z = 10 }, { x = 0, z = 0 } }
    local ok, err = YardZone.validate(fence, {})
    assertTrue(not ok)
    assertEquals(err, YardZone.ERROR.EDGE_TOO_SHORT)
    local clean = YardZone.cleanPolygon(fence)
    assertEquals(#clean, 4)
    assertEquals(clean[2].x, 10)
    assertTrue(YardZone.validate(clean, {}))
end)

test("cleaning leaves a good outline alone and never drops below a triangle", function()
    setup()
    local clean = YardZone.cleanPolygon(square(0, 0, 20))
    assertTrue(YardZone.samePolygon(clean, square(0, 0, 20)))
    local tiny = { { x = 0, z = 0 }, { x = 0.5, z = 0 }, { x = 0, z = 0.5 } }
    assertEquals(#YardZone.cleanPolygon(tiny), 3)
end)

test("an existing yard with a repeated closing corner can be edited and applied", function()
    setup()
    local e = YardZone.Editor.new()
    local saved = square(0, 0, 20)
    saved[5] = { x = 0, z = 0 }
    e:loadExisting(1, saved)
    assertEquals(#e.points, 4)
    assertTrue(e:validate({}))
    assertTrue(e:isDirty())
end)

test("bounds from an outline", function()
    setup()
    local b = YardZone.boundsFromPolygon({ { x = 2, z = 3 }, { x = 12, z = 3 }, { x = 12, z = 23 } })
    assertNear(b.cx, 7, 1e-9)
    assertNear(b.cz, 13, 1e-9)
    assertNear(b.sizeX, 10, 1e-9)
    assertNear(b.sizeZ, 20, 1e-9)
    assertEquals(#b.polygon, 3)
    assertEquals(b.anchorX, 2)
end)

test("a legacy yard without a polygon is outlined by its box", function()
    setup()
    local p = YardZone.polygonOfBounds({ cx = 10, cz = 10, sizeX = 4, sizeZ = 6 })
    assertEquals(#p, 4)
    assertNear(YardZone.area(p), 24, 1e-9)
end)

-- Editor -------------------------------------------------------------------------------------

test("draw a yard: corners, then click the first corner to close it", function()
    setup()
    local e = YardZone.Editor.new()
    e:startNew(0, 0)
    assertEquals(e.state, YardZone.STATE.DRAWING)
    assertEquals(e:addPoint(20, 0), "added")
    assertEquals(e:addPoint(20, 20), "added")
    assertEquals(e:addPoint(0.5, 0.5), "closed", "near the first corner")
    assertEquals(e.state, YardZone.STATE.EDITING)
    assertEquals(#e.points, 3)
    assertTrue(e:validate({}))
end)

test("the outline can't be closed before it has three corners", function()
    setup()
    local e = YardZone.Editor.new()
    e:startNew(0, 0)
    e:addPoint(20, 0)
    assertTrue(not e:canClose())
    assertEquals(e:addPoint(0.2, 0.2), nil, "too close to the last corner... or the first")
end)

test("a corner that would cross the outline is refused", function()
    setup()
    local e = YardZone.Editor.new()
    e:startNew(0, 0)
    e:addPoint(20, 0)
    e:addPoint(20, 20)
    e:addPoint(10, 20)
    assertEquals(e:addPoint(10, -10), nil, "crosses the first edge")
    assertEquals(#e.points, 4)
end)

test("corners too close together are refused", function()
    setup()
    local e = YardZone.Editor.new()
    e:startNew(0, 0)
    assertEquals(e:addPoint(0.5, 0), nil)
    assertEquals(#e.points, 1)
end)

test("taking back corners while drawing, down to nothing", function()
    setup()
    local e = YardZone.Editor.new()
    e:startNew(0, 0)
    e:addPoint(20, 0)
    assertTrue(e:removeLastPoint())
    assertEquals(#e.points, 1)
    assertTrue(e:removeLastPoint())
    assertEquals(e.state, YardZone.STATE.IDLE)
end)

test("dragging a corner moves it, and one undo puts it back", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(7, square(0, 0, 20))
    assertTrue(not e:isDirty())
    local index = e:pickVertex(20.4, 20.3)
    assertEquals(index, 3)
    e:beginDrag(index)
    e:dragTo(25, 22)
    e:dragTo(30, 30)
    e:endDrag()
    assertEquals(e.points[3].x, 30)
    assertTrue(e:isDirty())
    assertTrue(e:undo())
    assertEquals(e.points[3].x, 20)
    assertTrue(not e:isDirty())
    assertTrue(not e:canUndo())
end)

test("a click on a corner without moving leaves no undo step", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, square(0, 0, 20))
    e:beginDrag(1)
    e:endDrag()
    assertTrue(not e:canUndo())
end)

test("a cancelled drag restores the corner", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, square(0, 0, 20))
    e:beginDrag(2)
    e:dragTo(40, 0)
    e:cancelDrag()
    assertEquals(e.points[2].x, 20)
    assertTrue(not e:isDirty())
end)

test("pressing on an edge adds a corner there and drags it, as one undo step", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, square(0, 0, 20))
    local edge, px, pz = e:pickEdge(10, -0.4)
    assertEquals(edge, 1)
    local index = e:insertAndDrag(edge, px, pz)
    assertEquals(index, 2)
    e:dragTo(10, -8)
    e:endDrag()
    assertEquals(#e.points, 5)
    assertEquals(e.points[2].z, -8)
    e:undo()
    assertEquals(#e.points, 4)
end)

test("a click on an edge without dragging adds no corner", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, square(0, 0, 20))
    -- Next to corner 2 (20, 0): out of corner reach, but the edge point is under 1 m from it.
    assertEquals(e:pickVertex(19.05, -1.19), nil)
    local edge, px, pz = e:pickEdge(19.05, -1.19)
    assertEquals(edge, 1)
    assertTrue(20 - px < 1.0)
    e:insertAndDrag(edge, px, pz)
    e:endDrag()
    assertEquals(#e.points, 4)
    assertTrue(not e:canUndo())
    assertTrue(not e:isDirty())
    assertTrue(e:validate({}))
end)

test("a corner dragged onto its neighbour merges into it", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, { { x = 0, z = 0 }, { x = 10, z = 0 }, { x = 20, z = 0 }, { x = 20, z = 20 }, { x = 0, z = 20 } })
    e:beginDrag(2)
    e:dragTo(19.6, 0.2)
    e:endDrag()
    assertEquals(#e.points, 4)
    assertEquals(e.points[2].x, 20)
    assertTrue(e:validate({}))
    assertTrue(e:undo())
    assertEquals(#e.points, 5)
    assertEquals(e.points[2].x, 10)
end)

test("a new corner dragged back onto a neighbour is dropped", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, square(0, 0, 20))
    local edge, px, pz = e:pickEdge(10, -0.4)
    e:insertAndDrag(edge, px, pz)
    e:dragTo(0.5, 0)
    e:endDrag()
    assertEquals(#e.points, 4)
    assertTrue(e:validate({}))
end)

test("a triangle's corner dragged onto a neighbour stays (too few to merge)", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, { { x = 0, z = 0 }, { x = 20, z = 0 }, { x = 0, z = 20 } })
    e:beginDrag(2)
    e:dragTo(0.5, 0)
    e:endDrag()
    assertEquals(#e.points, 3)
    local ok, err = e:validate({})
    assertTrue(not ok)
    assertEquals(err, YardZone.ERROR.EDGE_TOO_SHORT)
end)

test("corners can be deleted down to a triangle", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, square(0, 0, 20))
    assertTrue(e:deleteVertex(4))
    assertEquals(#e.points, 3)
    assertTrue(not e:deleteVertex(1), "not below three corners")
end)

test("closing is undoable back to drawing", function()
    setup()
    local e = YardZone.Editor.new()
    e:startNew(0, 0)
    e:addPoint(20, 0)
    e:addPoint(20, 20)
    e:close()
    assertEquals(e.state, YardZone.STATE.EDITING)
    e:undo()
    assertEquals(e.state, YardZone.STATE.DRAWING)
    assertEquals(#e.points, 3)
end)

test("a new outline is dirty as soon as it has a corner; an untouched existing one isn't", function()
    setup()
    local e = YardZone.Editor.new()
    assertTrue(not e:isDirty())
    e:startNew(0, 0)
    assertTrue(e:isDirty())
    e:loadExisting(3, square(0, 0, 20))
    assertTrue(not e:isDirty())
end)

test("editing an outline into another yard is invalid", function()
    setup()
    local e = YardZone.Editor.new()
    e:loadExisting(1, square(0, 0, 20))
    e:beginDrag(2)
    e:dragTo(35, 0)
    e:endDrag()
    local ok, err = e:validate({ square(30, -10, 20) })
    assertTrue(not ok)
    assertEquals(err, YardZone.ERROR.OVERLAPS_YARD)
end)

test("every change bumps the version, so previews know to refresh", function()
    setup()
    local e = YardZone.Editor.new()
    local v = e.version
    e:startNew(0, 0)
    assertTrue(e.version > v)
    v = e.version
    e:addPoint(20, 0)
    assertTrue(e.version > v)
end)
